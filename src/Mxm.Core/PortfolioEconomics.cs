namespace Mxm.Core;

// This pure C# research kernel has no trading or broker API calls.
// Chronological source admission and independent confirmation are mandatory:
// a profitable synthetic fixture MUST NOT be promoted.
public sealed record StudyWindow(
    DateTime DevelopmentStartUtc,
    DateTime SelectionStartUtc,
    DateTime ConfirmationStartUtc,
    DateTime EndUtc);

public sealed record CompletedPortfolioTrade(
    long PositionId, DateTime OpenUtc, DateTime CloseUtc,
    decimal GrossEur, decimal? EntryCommissionEur, decimal? ExitCommissionEur,
    decimal? ExecutionSlippageEur, decimal? FinancingEur,
    decimal? ConversionCostEur, string EvidenceSha256,
    bool OpeningAndClosingHistoryComplete);

public sealed record LiquidationEquityMark(DateTime TimeUtc, decimal EquityEur,
    bool ExposureAndAccruedCostsComplete);

public sealed record EconomicProof(
    bool AuthenticPepperstoneSource,
    bool ContinuousAccountAndFundingHistory,
    bool BidAskFillSizeMarginAndSlippageProven,
    bool AllCostsAndCurrencyConversionsProven,
    bool EligibilityDeclaredBeforeOutcomes,
    bool NoChronologicalSelectionLeakage,
    bool IndependentConfirmationNetEdgeProven,
    bool FlatAndReconciledAtStudyBoundaries,
    decimal? CertifiedGlobalEquityFloorEur,
    decimal? CertifiedGlobalEquityPeakUpperEur);

public sealed record EconomicResult(
    decimal StartCapitalEur, decimal ClosedNetEur, decimal ConfirmationNetEur,
    decimal FinalRealizedBalanceEur, decimal ObservedMaxDrawdown,
    decimal? CertifiedMaxDrawdownUpperBound, int EligibleWeeks,
    int MinimumCompleteRoundTripsPerEligibleWeek, bool Pass,
    string Verdict);

// Only complete, position-level round trips count; partial exits never multiply trades.
// Positions may overlap. Proof flags are not generated by this evaluator.
public static class PortfolioEconomics
{
    public const decimal OwnerInitialCapitalEur = 200m;
    public const decimal OwnerMaxDrawdown = 0.30m;
    public const int OwnerMinimumWeeklyRoundTrips = 21;

    private static bool Utc(DateTime d) => d.Kind == DateTimeKind.Utc;
    private static bool Hex64(string? hash) =>
        hash is { Length: 64 } && hash.All(Uri.IsHexDigit);

    public static EconomicResult Evaluate(
        StudyWindow window,
        IEnumerable<CompletedPortfolioTrade> roundTrips,
        IEnumerable<LiquidationEquityMark> liquidationEquity,
        IEnumerable<DateTime> predeclaredEligibleWeekStarts,
        EconomicProof proof)
    {
        ArgumentNullException.ThrowIfNull(roundTrips);
        ArgumentNullException.ThrowIfNull(liquidationEquity);
        ArgumentNullException.ThrowIfNull(predeclaredEligibleWeekStarts);
        ArgumentNullException.ThrowIfNull(proof);
        if (!Utc(window.DevelopmentStartUtc) || !Utc(window.SelectionStartUtc) ||
            !Utc(window.ConfirmationStartUtc) || !Utc(window.EndUtc) ||
            !(window.DevelopmentStartUtc < window.SelectionStartUtc &&
              window.SelectionStartUtc < window.ConfirmationStartUtc &&
              window.ConfirmationStartUtc < window.EndUtc))
            throw new ArgumentException("STUDY_SPLITS_MUST_BE_CHRONOLOGICAL_UTC");

        // A minimum of twelve *calendar months* across all chronological splits,
        // not an inferred/annualized score from a seven-day H1 sample.
        bool yearPresent = window.DevelopmentStartUtc.AddMonths(12) <= window.EndUtc;
        var trades = roundTrips.ToArray();
        var marks = liquidationEquity.ToArray();
        var weeks = predeclaredEligibleWeekStarts.ToArray();
        if (trades.GroupBy(t => t.PositionId).Any(g => g.Count() != 1))
            throw new ArgumentException("DUPLICATE_PORTFOLIO_POSITION");
        foreach (var t in trades)
        {
            if (t.PositionId <= 0 || !Utc(t.OpenUtc) || !Utc(t.CloseUtc) ||
                t.OpenUtc < window.DevelopmentStartUtc || t.OpenUtc >= t.CloseUtc ||
                t.CloseUtc >= window.EndUtc || !t.OpeningAndClosingHistoryComplete ||
                !Hex64(t.EvidenceSha256) ||
                t.EntryCommissionEur is not decimal entry || entry < 0 ||
                t.ExitCommissionEur is not decimal exit || exit < 0 ||
                t.ExecutionSlippageEur is not decimal slip || slip < 0 ||
                t.FinancingEur is null ||
                t.ConversionCostEur is not decimal fx || fx < 0)
                throw new ArgumentException("INCOMPLETE_OR_UNPRICED_ROUND_TRIP");
            // A trade crossing a split is not assigned optimistic costs to the
            // confirmation bucket; such trades require a distinct evidence policy.
            if ((t.OpenUtc < window.SelectionStartUtc && t.CloseUtc >= window.SelectionStartUtc) ||
                (t.OpenUtc < window.ConfirmationStartUtc && t.CloseUtc >= window.ConfirmationStartUtc))
                throw new ArgumentException("CROSS_SPLIT_ROUND_TRIP");
        }
        if (marks.Length < 2 || marks[0].TimeUtc != window.DevelopmentStartUtc ||
            marks[^1].TimeUtc != window.EndUtc ||
            marks[0].EquityEur != OwnerInitialCapitalEur)
            throw new ArgumentException("LIQUIDATION_BOUNDARY_MISSING");
        for (int i = 0; i < marks.Length; i++)
        {
            var m = marks[i];
            if (!Utc(m.TimeUtc) || !m.ExposureAndAccruedCostsComplete ||
                m.EquityEur <= 0 ||
                (i > 0 && marks[i-1].TimeUtc >= m.TimeUtc))
                throw new ArgumentException("LIQUIDATION_SERIES_INVALID");
        }
        if (weeks.Distinct().Count() != weeks.Length || weeks.Any(w =>
            !Utc(w) || w.DayOfWeek != DayOfWeek.Monday || w.TimeOfDay != TimeSpan.Zero ||
            w < window.ConfirmationStartUtc || w.AddDays(7) > window.EndUtc))
            throw new ArgumentException("ELIGIBLE_WEEKS_NOT_PREDECLARED_AS_FULL_UTC_WEEKS");

        decimal Net(CompletedPortfolioTrade t) =>
            t.GrossEur - t.EntryCommissionEur!.Value -
            t.ExitCommissionEur!.Value - t.ExecutionSlippageEur!.Value +
            t.FinancingEur!.Value - t.ConversionCostEur!.Value;
        var net = trades.Sum(Net);
        var confirmationNet = trades.Where(t => t.CloseUtc >= window.ConfirmationStartUtc).Sum(Net);
        var finalBalance = OwnerInitialCapitalEur + net;
        var peak = OwnerInitialCapitalEur;
        var observedMaxDrawdown = 0m;
        foreach (var m in marks)
        {
            peak = Math.Max(peak, m.EquityEur);
            observedMaxDrawdown = Math.Max(observedMaxDrawdown, 1m - m.EquityEur / peak);
        }
        // This is a *sampled* DD: not a proof of the global peak or intra-mark trough.
        decimal? certifiedDd = null;
        if (proof.CertifiedGlobalEquityFloorEur is decimal floor &&
            proof.CertifiedGlobalEquityPeakUpperEur is decimal upper)
        {
            if (floor <= 0 || upper < OwnerInitialCapitalEur ||
                floor > marks.Min(x => x.EquityEur) ||
                upper < marks.Max(x => x.EquityEur))
                throw new ArgumentException("CERTIFIED_EQUITY_EXTREMA_CONTRADICT_MARKS");
            certifiedDd = 1m - floor / upper;
        }

        int weeklyMin = weeks.Length == 0 ? 0 : weeks.Min(w =>
            trades.Count(t => t.CloseUtc >= w && t.CloseUtc < w.AddDays(7)));
        string verdict =
            !yearPresent ? "LESS_THAN_TWELVE_CALENDAR_MONTHS" :
            !proof.AuthenticPepperstoneSource ? "AUTHENTIC_SOURCE_NOT_PROVEN" :
            !proof.ContinuousAccountAndFundingHistory ? "CONTINUOUS_ACCOUNT_HISTORY_NOT_PROVEN" :
            !proof.BidAskFillSizeMarginAndSlippageProven ? "EXECUTABLE_FILLS_AND_MARGIN_NOT_PROVEN" :
            !proof.AllCostsAndCurrencyConversionsProven ? "FULL_NET_COSTS_NOT_PROVEN" :
            !proof.EligibilityDeclaredBeforeOutcomes ? "ELIGIBILITY_NOT_PREDECLARED" :
            !proof.NoChronologicalSelectionLeakage ? "SELECTION_LEAKAGE_NOT_EXCLUDED" :
            !proof.FlatAndReconciledAtStudyBoundaries ||
                marks[^1].EquityEur != finalBalance ? "CAPITAL_AND_EQUITY_NOT_RECONCILED" :
            weeks.Length == 0 || weeklyMin < OwnerMinimumWeeklyRoundTrips ? "HARD21_NOT_DEMONSTRATED" :
            certifiedDd is null ? "GLOBAL_DRAWDOWN_BOUND_NOT_PROVEN" :
            certifiedDd >= OwnerMaxDrawdown ? "DRAWDOWN_LIMIT" :
            confirmationNet <= 0m ? "CONFIRMATION_NET_NOT_POSITIVE" :
            !proof.IndependentConfirmationNetEdgeProven ? "INDEPENDENT_NET_EDGE_NOT_PROVEN" :
            "ALL_EVIDENCE_GATES_PASSED";
        return new EconomicResult(OwnerInitialCapitalEur, net, confirmationNet,
            finalBalance, observedMaxDrawdown, certifiedDd, weeks.Length, weeklyMin,
            verdict == "ALL_EVIDENCE_GATES_PASSED", verdict);
    }
}
